// Writes dist/sw.js: a service worker that caches every built file so the web game runs offline.
import { readdirSync, statSync, writeFileSync, readFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';

const dist = fileURLToPath(new URL('../dist/', import.meta.url));
const entries = [];
(function walk(dir) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p);
    else if (name !== 'sw.js') entries.push({ rel: './' + relative(dist, p).split('\\').join('/'), abs: p });
  }
})(dist);
entries.sort((a, b) => a.rel.localeCompare(b.rel));
const files = entries.map(e => e.rel);
const hash = createHash('sha256');
for (const e of entries) {
  hash.update(e.rel);
  hash.update(readFileSync(e.abs));
}
const version = hash.digest('hex').slice(0, 12);
const sw = `// Generated by scripts/gen-sw.mjs. Do not edit.
const CACHE = 'towerriot-${version}';
const FILES = ${JSON.stringify(['./', ...files], null, 0)};
self.addEventListener('install', e => {
  e.waitUntil(caches.open(CACHE).then(c => c.addAll(FILES)));
});
self.addEventListener('message', e => {
  if (e.data && e.data.type === 'SKIP_WAITING') self.skipWaiting();
});
self.addEventListener('activate', e => {
  e.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(k => k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener('fetch', e => {
  if (e.request.method !== 'GET') return;
  const url = new URL(e.request.url);
  if (url.origin !== self.location.origin) return;
  e.respondWith(
    caches.match(e.request, { ignoreSearch: true, ignoreVary: true }).then(hit => {
      if (hit) return hit;
      return fetch(e.request).catch(() => e.request.mode === 'navigate' ? caches.match('./index.html') : Response.error());
    }),
  );
});
`;
writeFileSync(join(dist, 'sw.js'), sw);
console.log(`sw.js: ${files.length} files cached as ${version}`);
