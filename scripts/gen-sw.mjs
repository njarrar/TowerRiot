// Writes dist/sw.js: a service worker that caches every built file so the web game runs offline.
import { readdirSync, statSync, writeFileSync, readFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { createHash } from 'node:crypto';

const dist = new URL('../dist/', import.meta.url).pathname;
const files = [];
const hash = createHash('sha256');
(function walk(dir) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p);
    else if (name !== 'sw.js') { files.push('./' + relative(dist, p).split('\\').join('/')); hash.update(readFileSync(p)); }
  }
})(dist);
files.sort();
const version = hash.digest('hex').slice(0, 12);
const sw = `// Generated by scripts/gen-sw.mjs. Do not edit.
const CACHE = 'towerriot-${version}';
const FILES = ${JSON.stringify(['./', ...files], null, 0)};
self.addEventListener('install', e => {
  e.waitUntil(caches.open(CACHE).then(c => c.addAll(FILES)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', e => {
  e.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(k => k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener('fetch', e => {
  if (e.request.method !== 'GET') return;
  e.respondWith(caches.match(e.request, { ignoreSearch: true }).then(hit => hit || fetch(e.request).catch(() => caches.match('./index.html'))));
});
`;
writeFileSync(join(dist, 'sw.js'), sw);
console.log(`sw.js: ${files.length} files cached as ${version}`);
